// Helper function to get tool by ID
export const getToolById = (id) => toolsConfig.find(tool => tool.id === id);

// Helper function to get related tools
export const getRelatedTools = (toolId) => {
  const tool = getToolById(toolId);
  if (!tool || !tool.relatedTools) return [];
  return tool.relatedTools.map(id => getToolById(id)).filter(Boolean);
};

// Helper function to filter tools by category
export const getToolsByCategory = (category) => 
  toolsConfig.filter(tool => tool.category === category);

// Helper function to filter tools by audience
export const getToolsByAudience = (audience) => 
  toolsConfig.filter(tool => tool.audience.includes(audience));

// Helper function to get live tools
export const getLiveTools = () => toolsConfig.filter(tool => !tool.comingSoon);

// Helper function to get coming soon tools
export const getComingSoonTools = () => toolsConfig.filter(tool => tool.comingSoon);

